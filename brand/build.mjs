#!/usr/bin/env node
// Generates brand/tokens.css from brand/tokens.json.
//   node brand/build.mjs           write tokens.css
//   node brand/build.mjs --check   exit 1 if tokens.css is out of date (CI)
//   node brand/build.mjs --contrast print WCAG contrast ratios for every state colour
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const tokens = JSON.parse(readFileSync(join(here, 'tokens.json'), 'utf8'));

const kebab = (s) => s.replace(/[A-Z]/g, (c) => '-' + c.toLowerCase());

function themeVars(t) {
  const v = [];
  for (const [k, val] of Object.entries(t.color)) v.push([`--rs-color-${kebab(k)}`, val]);
  t.series.forEach((c, i) => v.push([`--rs-series-${i + 1}`, c]));
  for (const [state, { bg, on }] of Object.entries(t.state)) {
    v.push([`--rs-state-${state}`, bg]);
    v.push([`--rs-state-${state}-on`, on]);
  }
  v.push(['--rs-font-scale', String(t.fontScale)]);
  v.push(['--rs-border-width', `${t.borderWidth}px`]);
  for (const [k, px] of Object.entries(tokens.size)) {
    if (k.startsWith('$')) continue;
    v.push([`--rs-size-${kebab(k)}`, `calc(${px}px * var(--rs-font-scale))`]);
  }
  return v;
}

function shared() {
  const v = [
    ['--rs-font-ui', tokens.font.ui],
    ['--rs-font-mono', tokens.font.mono],
    ['--rs-line-height', String(tokens.font.lineHeight)],
    ['--rs-touch-min', `${tokens.touchMin}px`],
  ];
  for (const [k, w] of Object.entries(tokens.font.weight)) v.push([`--rs-weight-${k}`, String(w)]);
  for (const [k, px] of Object.entries(tokens.radius)) v.push([`--rs-radius-${kebab(k)}`, `${px}px`]);
  for (const [k, px] of Object.entries(tokens.space)) v.push([`--rs-space-${k}`, `${px}px`]);
  for (const [k, s] of Object.entries(tokens.shadow)) v.push([`--rs-shadow-${k}`, s]);
  for (const [k, c] of Object.entries(tokens.brand)) v.push([`--rs-brand-${k}`, c]);
  return v;
}

const block = (sel, vars) => `${sel} {\n${vars.map(([k, v]) => `  ${k}: ${v};`).join('\n')}\n}\n`;

function css() {
  const { standard, dark, sunlight } = tokens.themes;
  return [
    '/* GENERATED by brand/build.mjs from brand/tokens.json. Do not edit. */\n',
    block(':root', shared()),
    block(':root,\n[data-theme="standard"]', themeVars(standard)),
    `@media (prefers-color-scheme: dark) {\n${block(':root:not([data-theme])', themeVars(dark))
      .split('\n')
      .map((l) => (l ? '  ' + l : l))
      .join('\n')}}\n`,
    block('[data-theme="dark"]', themeVars(dark)),
    block('[data-theme="sunlight"]', themeVars(sunlight)),
  ].join('\n');
}

// WCAG 2.x relative luminance and contrast.
function lum(hex) {
  const n = parseInt(hex.slice(1), 16);
  const ch = [(n >> 16) & 255, (n >> 8) & 255, n & 255].map((c) => {
    const s = c / 255;
    return s <= 0.03928 ? s / 12.92 : ((s + 0.055) / 1.055) ** 2.4;
  });
  return 0.2126 * ch[0] + 0.7152 * ch[1] + 0.0722 * ch[2];
}
export function contrast(a, b) {
  const [x, y] = [lum(a), lum(b)].sort((p, q) => q - p);
  return (x + 0.05) / (y + 0.05);
}

const out = css();
const path = join(here, 'tokens.css');
const args = process.argv.slice(2);
if (args.includes('--contrast')) {
  let failed = false;
  for (const [name, t] of Object.entries(tokens.themes)) {
    for (const [state, { bg, on }] of Object.entries(t.state)) {
      const r = contrast(bg, on);
      const min = name === 'sunlight' ? 7 : 4.5;
      if (r < min) failed = true;
      console.log(`${name.padEnd(9)} ${state.padEnd(13)} ${bg} on ${on}  ${r.toFixed(2)}:1 ${r < min ? `FAIL (< ${min})` : 'ok'}`);
    }
    const r = contrast(t.color.text, t.color.background);
    console.log(`${name.padEnd(9)} text/background ${r.toFixed(2)}:1`);
  }
  process.exit(failed ? 1 : 0);
} else if (args.includes('--check')) {
  if (!existsSync(path) || readFileSync(path, 'utf8') !== out) {
    console.error('brand/tokens.css is out of date: run `node brand/build.mjs`');
    process.exit(1);
  }
} else {
  writeFileSync(path, out);
  console.log(`wrote ${path}`);
}
